const IDLE_BOB = [0, 0, 1, 1];
const RUN_BOB = [0, 1, 0, 0, 1, 0];

// Dash frames are run poses dissolved into mist by this amount (0 = intact, 1 = all mist).
const MIST = [0.35, 0.8];

function frames(): Record<string, Layer[]> {
  const f: Record<string, Layer[]> = { shadow: [[9, 24, SHADOW]], mote: [[16, 16, ['l']]] };
  for (const [v, d] of Object.entries(VIEWS)) {
    const pose = (legs: Grid, dy: number, hem: Grid, blink: boolean): Layer[] => [
      [OX, OY + HEM, legs], [OX, OY + dy, d.body], [OX, OY + HEM + dy, hem],
      ...(blink && d.blink ? [[OX + d.blink[0], OY + dy + d.blink[1], [d.blink[2]]] as Layer] : []),
    ];
    IDLE_BOB.forEach((dy, i) => {
      f[`${v}-idle${i}`] = pose(d.legs, dy, d.hems[i % 2], false);
      f[`${v}-blink${i}`] = pose(d.legs, dy, d.hems[i % 2], true);
    });
    d.run.forEach((legs, i) => {
      const dy = d.run.length === 4 ? i % 2 : RUN_BOB[i];
      const flap = Math.floor((i * 2) / d.run.length); // the cape flaps once per stride
      f[`${v}-run${i}`] = 'runBodies' in d
        ? [[OX, OY + HEM, legs], [OX - 4, OY + dy, d.runBodies[flap]]]
        : pose(legs, dy, d.runHems[flap], false);
    });
    SLASHES[v as keyof typeof VIEWS].forEach(([x, y, arm], i) => {
      const base = 'runBodies' in d ? [[OX, OY + HEM, d.run[0]], [OX - 4, OY + 1, d.runBodies[0]]] as Layer[] : pose(d.legs, 0, d.runHems[i], false);
      f[`${v}-slash${i}`] = [...base, [OX + x, OY + y, arm]];
    });
    MIST.forEach((_, i) => (f[`${v}-dash${i}`] = f[`${v}-run${d.run.length === 6 ? 2 : 1}`]));
  }
  return f;
}

// Deterministic per-pixel noise in [0, 1).
const noise = (x: number, y: number) => (((x * 73856093) ^ (y * 19349663)) >>> 0) % 997 / 997;

// Turns part of one frame into a two-tone mist silhouette that streams behind the motion (tx, ty).
// More of the body goes to mist at the feet and at the trailing side; the eyes stay lit.
function dissolve(ctx: CanvasRenderingContext2D, fx: number, amount: number, tx: number, ty: number) {
  const img = ctx.getImageData(fx, 0, FW, FW), p = img.data;
  const at = (x: number, y: number) => (y * FW + x) * 4;
  const light = [0x8a, 0x6f, 0x8f], dark = [0x5a, 0x44, 0x68];
  for (let y = 0; y < FW; y++) for (let x = 0; x < FW; x++) {
    const i = at(x, y);
    if (!p[i + 3] || (ty <= 0 && p[i] === 0xe0 && p[i + 1] === 0x28 && y < 13 && x > 12)) continue;
    // 2x2 clumps share their noise, so the edge of the mist is ragged without single-pixel static.
    const a = amount + (y - 16) / 24 + (tx * (x - 16) + ty * (y - 16)) / 30 + (noise(x >> 1, y >> 1) - 0.5) * 0.5;
    if (a > 0.5) p.set([...(p[i] + p[i + 1] + p[i + 2] > 300 ? light : dark), 230], i);
  }
  // Streaks: most lines along the motion trail a wisp off the body's back edge.
  for (let l = 0; l < FW; l++) {
    if (noise(l, 3) < 0.4) continue;
    const pos = (k: number) => ((v) => (tx ? at(v, l) : at(l, v)))((tx || ty) < 0 ? k : FW - 1 - k);
    let k = 0;
    while (k < FW && !p[pos(k) + 3]) k++;
    if (k === FW || (p[pos(k)] !== light[0] && p[pos(k)] !== dark[0])) continue;
    const len = Math.min(k, Math.floor(amount * (3 + noise(l, 9) * 9)));
    for (let j = 1; j <= len; j++) p.set([...(j < 3 ? light : dark), 200 - j * 15], pos(k - j));
  }
  ctx.putImageData(img, fx, 0);
}

function bake(scene: Phaser.Scene) {
  const all = frames();
  const names = Object.keys(all);
  const tex = scene.textures.createCanvas('hero', FW * names.length, FW)!;
  const ctx = tex.context;
  names.forEach((name, i) => {
    for (const [x, y, rows] of all[name]) {
      rows.forEach((row, ry) => [...row].forEach((c, rx) => {
        const px = i * FW + x + rx, py = y + ry;
        if (c === '.') return;
        if (c === ',') return ctx.clearRect(px, py, 1, 1);
        if (!PAL[c]) throw new Error(`hero ${name}: unknown pixel '${c}'`);
        ctx.fillStyle = PAL[c];
        ctx.fillRect(px, py, 1, 1);
      }));
    }
    const dash = name.match(/^(\w+)-dash(\d)$/);
    if (dash) dissolve(ctx, i * FW, MIST[+dash[2]], dash[1] === 'side' ? -1 : 0, { side: 0, down: -1, up: 1 }[dash[1]]!);
    tex.add(name, 0, i * FW, 0, FW, FW);
  });
  tex.refresh();
}

// Per-hero animation memory: show() only gets the current look, so edges (slash start, dash end...) are kept here.
type State = { shadow: Phaser.GameObjects.Image; was: HeroLook; swing: number; slashAt: number; hurtAt: number; dashAt: number; dashEnd: number; ghostAt: number };
const states = new WeakMap<Phaser.Physics.Arcade.Sprite, State>();

export function create(scene: Phaser.Scene, x: number, y: number): Phaser.Physics.Arcade.Sprite {
  if (!scene.textures.exists('hero')) bake(scene);
  const s = scene.physics.add.sprite(x, y, 'hero', 'up-idle0');
  s.setSize(8, 6).setOffset(12, 21); // feet hitbox, the rest of the sprite overlaps freely
  const shadow = scene.add.image(x, y, 'hero', 'shadow');
  // Physics moves the sprite after update(), so the shadow follows on POST_UPDATE to avoid trailing a frame.
  const follow = () => shadow.setPosition(s.x, s.y).setDepth(s.depth - 0.5);
  scene.events.on(Phaser.Scenes.Events.POST_UPDATE, follow);
  s.once(Phaser.GameObjects.Events.DESTROY, () => scene.events.off(Phaser.Scenes.Events.POST_UPDATE, follow));
  const was = { moving: false, dashing: false, slashing: false, hurt: false, invulnerable: false, facing: 0 };
  states.set(s, { shadow, was, swing: 1, slashAt: -1e9, hurtAt: -1e9, dashAt: -1e9, dashEnd: -1e9, ghostAt: 0 });
  return s;
}

// A wisp of mist that rises and fades.
function mote(scene: Phaser.Scene, x: number, y: number, depth: number) {
  const m = scene.add.image(x, y, 'hero', 'mote').setDepth(depth).setAlpha(0.9);
  scene.tweens.add({ targets: m, y: y - Phaser.Math.Between(3, 8), alpha: 0, duration: Phaser.Math.Between(220, 420), onComplete: () => m.destroy() });
}

export function show(s: Phaser.Physics.Arcade.Sprite, look: HeroLook) {
  const st = states.get(s)!, scene = s.scene, now = scene.time.now;
  if (look.slashing && !st.was.slashing) { st.slashAt = now; st.swing ^= 1; } // alternate the two swings
  if (look.hurt && !st.was.hurt) st.hurtAt = now;
  if (look.dashing && !st.was.dashing) {
    st.dashAt = now;
    for (let i = 0; i < 6; i++) mote(scene, s.x + Phaser.Math.Between(-6, 6), s.y + Phaser.Math.Between(-10, 8), s.depth + 1);
  }
  if (!look.dashing && st.was.dashing) st.dashEnd = now;
  st.was = { ...look };

  const c = Math.cos(look.facing);
  const view = Math.abs(c) > 0.38 ? 'side' : Math.sin(look.facing) > 0 ? 'down' : 'up'; // diagonals use the side view
  let frame = `${now % 3600 < 140 ? 'blink' : 'idle'}${Math.floor(now / 260) % 4}`;
  if (look.dashing) frame = `dash${now - st.dashAt < 40 ? 0 : 1}`;
  else if (now - st.dashEnd < 70) frame = 'dash0'; // re-forming out of the mist
  else if (look.slashing && now - st.slashAt < 150) frame = `slash${st.swing}`;
  else if (look.moving) { const n = VIEWS[view].run.length; frame = `run${Math.floor(now / (540 / n)) % n}`; } // one stride pair per 540ms in every view
  s.setFrame(`${view}-${frame}`).setFlipX(view === 'side' && c < 0);

  // Mist dash: the body leaves fading afterimages and wisps behind it.
  if (look.dashing && now - st.ghostAt > 24) {
    st.ghostAt = now;
    const g = scene.add.image(s.x, s.y, 'hero', s.frame.name).setFlipX(s.flipX).setDepth(s.depth - 1).setAlpha(0.45);
    g.setTint(0x5a4468).setTintMode(Phaser.TintModes.FILL);
    scene.tweens.add({ targets: g, alpha: 0, duration: 200, onComplete: () => g.destroy() });
    mote(scene, s.x + Phaser.Math.Between(-5, 5), s.y + Phaser.Math.Between(-8, 8), s.depth - 1);
  }

  if (look.hurt) s.setTint(now - st.hurtAt < 60 ? 0xffffff : 0xe0284a).setTintMode(Phaser.TintModes.FILL);
  else s.clearTint();
  const blink = look.invulnerable && !look.hurt && Math.floor(now / 70) % 2 === 1;
  s.setAlpha(look.dashing ? 0.85 : blink ? 0.25 : 1);
  st.shadow.setAlpha(look.dashing ? 0.45 : 1).setScale(look.dashing ? 0.75 : 1);
}
