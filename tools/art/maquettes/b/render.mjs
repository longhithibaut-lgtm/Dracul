import { chromium } from 'playwright';
import fs from 'fs';
const dir = new URL('.', import.meta.url).pathname;
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('console', m => console.log('page:', m.text()));
page.on('pageerror', e => console.log('ERR', e.message));
await page.setContent('<canvas id=c></canvas>');
const t = Date.now();
await page.evaluate(m => { globalThis.MODE = m; }, process.env.MODE || 'final');
await page.addScriptTag({ content: fs.readFileSync(dir + 'scene.js', 'utf8') });
const [full, native] = await page.evaluate(() => {
  const s = document.createElement('canvas'); s.width = W; s.height = H;
  s.getContext('2d').putImageData(new ImageData(IMG, W, H), 0, 0);
  const c = document.getElementById('c'); c.width = W * 4; c.height = H * 4;
  const x = c.getContext('2d'); x.imageSmoothingEnabled = false; x.drawImage(s, 0, 0, W * 4, H * 4);
  return [c.toDataURL('image/png'), s.toDataURL('image/png')];
});
fs.writeFileSync(dir + (process.env.OUT || 'salle-b.png'), Buffer.from(full.split(',')[1], 'base64'));
fs.writeFileSync(dir + 'salle-b-480.png', Buffer.from(native.split(',')[1], 'base64'));
console.log('done', Date.now() - t, 'ms');
await browser.close();
