// Le coffre (docs/extraction.md §7), where the items brought back to the refuge are kept: the refuge mockup's own chest
// (tools/art/maquettes/hub3/props3.mjs chest(), the one of the wardrobe corner) rendered alone, lit like le Rongé
// (tools/art/ronge.gen.mjs: the cold rim, the warm fill, the hero's lantern off-frame) and snapped onto the mockup's
// palette, at the refuge's density (one texel a mockup px: the game draws it at half scale).
// Writes src/chest.png and src/chest.data.ts. Usage: node tools/art/chest.gen.mjs (a few seconds);
// PREVIEW=1 writes shots/chest-preview.png (x4, on grey) instead.
import { writeFileSync, mkdirSync } from 'node:fs';
import { camera, render, post, haze, L, writePNG } from './maquettes/hub3/lib.mjs';
import { chest } from './maquettes/hub3/props3.mjs';

const W0 = 120, H0 = 90, SOLE0 = 64; // the render cell; the chest's floor point on row SOLE0
const m = chest(2), P = { x: W0 / 2, y: 0 };
const sc = {
  W: W0, H: H0, cam: camera(38 * Math.PI / 180), off: -SOLE0, env: null, ambient: L('#1a1c1e').map((c) => c * 0.6),
  objects: [{ name: 'chest', pos: [P.x, P.y, 0], yaw: 0.2, sdf: m.sdf, mat: m.mat, bounds: m.bounds, step: m.step, id: 0 }],
  lights: [
    { p: [P.x + 30, P.y - 60, 75], c: L('#8098a2'), I: 5, r0: 90, R: 260, soft: 10 },
    { p: [P.x - 70, P.y + 70, 140], c: L('#a08a70'), I: 0.9, r0: 130, R: 420, soft: 12 },
    { p: [P.x + 28, P.y + 50, 60], c: L('#b8a68a'), I: 2.4, r0: 40, R: 170, soft: 6 }, // the vampire's lantern, off-frame
  ],
};
const img = render(sc);
haze(img, sc);
const px = post(img, { exposure: 3.4, vignette: 0, desat: 0.15, grain: 0.004, dither: 0.015 });
for (let p = 0; p < W0 * H0; p++) px[p * 4 + 3] = img.oid[p] >= 0 ? 255 : 0;
// Cropped to what it covers, a pixel of air round it, centred on its floor point.
let x0 = W0, y0 = H0, x1 = 0, y1 = 0;
for (let p = 0; p < W0 * H0; p++) if (px[p * 4 + 3]) {
  const x = p % W0, y = (p - x) / W0;
  [x0, y0, x1, y1] = [Math.min(x0, x), Math.min(y0, y), Math.max(x1, x), Math.max(y1, y)];
}
const half = Math.max(W0 / 2 - x0, x1 + 1 - W0 / 2) + 1, FW = 2 * half, FH = y1 - y0 + 3, top = y0 - 1, left = W0 / 2 - half;
const rgba = new Uint8ClampedArray(FW * FH * 4);
for (let y = 0; y < FH; y++) for (let x = 0; x < FW; x++) {
  const sx = left + x, sy = top + y;
  if (sx >= 0 && sx < W0 && sy >= 0 && sy < H0) rgba.set(px.subarray((sy * W0 + sx) * 4, (sy * W0 + sx) * 4 + 4), (y * FW + x) * 4);
}
if (process.env.PREVIEW) {
  for (let p = 0; p < FW * FH; p++) if (!rgba[p * 4 + 3]) rgba.set([70, 70, 74, 255], p * 4);
  mkdirSync('shots', { recursive: true });
  writePNG('shots/chest-preview.png', rgba, FW, FH, 4);
} else {
  writePNG('src/chest.png', rgba, FW, FH, 1, true);
  writeFileSync('src/chest.data.ts', `// Generated by tools/art/chest.gen.mjs: edit it there, not this table.
// Le coffre's sprite (src/chest.png), FW x FH texels, its floor point on row SOLE, centred.
export const FW = ${FW}, FH = ${FH}, SOLE = ${SOLE0 - top};
`);
}
console.log(`chest ${FW}x${FH}, floor on row ${SOLE0 - top}`);
