// Vesna la Grise (docs/lore.md), the Rat house's chief, for the game: the refuge mockup's own model
// (tools/art/maquettes/hub3/chiefs3.mjs vesna(): the hooded old fence, grey shawl in patches, sharp chin, grey locks, a
// chain of coins and a rat's skull at her throat, her cane and a jar of blood) with her rats on her (one on her shoulder,
// one on her sack, two at her feet), lit like the foes and le Rongé (tools/art/ronge.gen.mjs: the cold rim, the warm
// fill, the hero's lantern off-frame). One view, facing the camera: standing, breathing (idle0-3); the gesture, a coin
// held up to her eye (count0-1). The cells are cropped to what all frames cover, her feet on row SOLE, centred.
// Writes src/vesna.png and src/vesna.data.ts. Usage: node tools/art/vesna.gen.mjs; PREVIEW=1 writes shots/vesna-preview.png.
import { writeFileSync, mkdirSync } from 'node:fs';
import { camera, render, post, haze, L } from './maquettes/grand/lib.mjs';
import { writePNG } from './grand/lib.mjs'; // keeps the alpha channel
import { vesna, rats } from './maquettes/hub3/chiefs3.mjs';

const cam = camera(38 * Math.PI / 180);
const W0 = 160, H0 = 160, SOLE0 = 124;
const RATS = rats([[8, 2, 67, 1.6], [2, -11, 58, -1.2], [9, 12, 0, 0.6], [-11, 10, 0, 2.5]]);
const FRAMES = [...[0, 0.5, 1, 0.5].map((b, k) => [`idle${k}`, 'stand', b]), ...[0, 1].map((b, k) => [`count${k}`, 'count', b])];

/** Her, pose `p`, breathing by `b` (0-1): heights stretched a little. */
function her(p, b) {
  const m = vesna(p), sz = 1 + 0.015 * b;
  return { ...m, sdf: (x, y, z) => m.sdf(x, y, z / sz), mat: (k, x, y, z, ...n) => m.mat(k, x, y, z / sz, ...n), bounds: [m.bounds[0], m.bounds[1], m.bounds[2], m.bounds[3], m.bounds[4], m.bounds[5] * sz] };
}

function frame([, p, b]) {
  const m = her(p, b), X = { x: W0 / 2, y: 0 };
  const sc = {
    W: W0, H: H0, cam, off: -SOLE0, env: null, ambient: L('#1a1c1e').map((c) => c * 0.6),
    objects: [{ name: 'vesna', pos: [X.x, X.y, 0], yaw: 0, sdf: m.sdf, mat: m.mat, bounds: m.bounds, id: 1, step: m.step ?? 0.6 },
      { name: 'rats', pos: [X.x, X.y, 0], yaw: 0, sdf: RATS.sdf, mat: RATS.mat, bounds: RATS.bounds, id: 2, step: RATS.step }],
    lights: [
      { p: [X.x + 30, X.y - 60, 75], c: L('#8098a2'), I: 7, r0: 90, R: 260, soft: 10, only: ['vesna', 'rats'] },
      { p: [X.x - 70, X.y + 70, 140], c: L('#a08a70'), I: 0.9, r0: 130, R: 420, soft: 12 },
      { p: [X.x + 28, X.y + 50, 60], c: L('#b8a68a'), I: 2.4, r0: 40, R: 170, soft: 6 }, // the vampire's lantern, off-frame
      { p: [X.x - 30, X.y + 30, 80], c: L('#b8a890'), I: 0.8, r0: 40, R: 160, soft: 6 }, // her shop's lamp
    ],
  };
  const img = render(sc);
  haze(img, sc);
  const px = post(img, { exposure: 3.4, vignette: 0, desat: 0.15, grain: 0.004, dither: 0.015 });
  for (let i = 0; i < W0 * H0; i++) px[i * 4 + 3] = img.oid[i] >= 0 ? 255 : 0;
  return px;
}

const t0 = Date.now(), cells = FRAMES.map(frame);
let x0 = W0, y0 = H0, x1 = 0, y1 = 0;
for (const px of cells) for (let p = 0; p < W0 * H0; p++) if (px[p * 4 + 3]) {
  const x = p % W0, y = (p - x) / W0;
  [x0, y0, x1, y1] = [Math.min(x0, x), Math.min(y0, y), Math.max(x1, x), Math.max(y1, y)];
}
const half = Math.max(W0 / 2 - x0, x1 + 1 - W0 / 2) + 1, FW = 2 * half, FH = y1 - y0 + 3, top = y0 - 1, left = W0 / 2 - half, W = FW * FRAMES.length;
const rgba = new Uint8ClampedArray(W * FH * 4);
cells.forEach((px, i) => {
  for (let y = 0; y < FH; y++) for (let x = 0; x < FW; x++) {
    const sx = left + x, sy = top + y;
    if (sx >= 0 && sx < W0 && sy >= 0 && sy < H0) rgba.set(px.subarray((sy * W0 + sx) * 4, (sy * W0 + sx) * 4 + 4), (y * W + i * FW + x) * 4);
  }
});
if (process.env.PREVIEW) {
  for (let p = 0; p < W * FH; p++) if (!rgba[p * 4 + 3]) rgba.set([70, 70, 74, 255], p * 4);
  mkdirSync('shots', { recursive: true });
  writePNG('shots/vesna-preview.png', rgba, W, FH, 3);
} else {
  writePNG('src/vesna.png', rgba, W, FH);
  writeFileSync('src/vesna.data.ts', `// Generated by tools/art/vesna.gen.mjs: edit her there (her model: tools/art/maquettes/hub3/chiefs3.mjs), not this table.
// Vesna's sheet (src/vesna.png): one row of FW x FH cells, her soles on row SOLE, centred; facing the camera.
export const FW = ${FW}, FH = ${FH}, SOLE = ${SOLE0 - top};
export const FRAMES = ${JSON.stringify(FRAMES.map(([n]) => n))};
`);
}
console.log(`${FRAMES.length} frames ${FW}x${FH}, soles on row ${SOLE0 - top}, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
