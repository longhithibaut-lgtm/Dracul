// Le Rongé (docs/lore.md), the refuge's merchant: the design the user chose, « accroupi au bassin »
// (tools/art/maquettes/ronge/ronge.mjs bassin(), docs/maquettes/ronge-1-bassin.png). A man who was a vampire, half gone
// ghoul, perched on the basin's rim like a gargoyle in the rags of a vampire's coat. Lit as the mockup's sprite was
// (tools/art/maquettes/ronge/card.mjs SPRITE=1: the foes' cold back light, warm fill, the hero's lantern off-frame).
// One view, three-quarter facing down-right (the game mirrors it toward the basin): the blood cupped at his mouth,
// breathing and drinking (idle0-3); leaning out to speak, a wet hand held open (look0-3); gone beast on hands and feet,
// heaving (beast0-1). His floor point is the floor under the rim (the model is lifted by RIM): a dark smudge on the rim
// under his feet. The cells are cropped to what all frames cover.
// Writes src/ronge.png and src/ronge.data.ts. Usage: node tools/art/ronge.gen.mjs (about half a minute);
// PREVIEW=1 writes shots/ronge-preview.png (x2, on grey) instead.
import { writeFileSync, mkdirSync } from 'node:fs';
import { camera, render, post, haze, L } from './maquettes/ennemis/lib.mjs';
import { place } from './maquettes/ennemis/fx.mjs';
import { writePNG } from './grand/lib.mjs'; // keeps the alpha channel
import { bassin } from './maquettes/ronge/ronge.mjs';

const cam = camera(38 * Math.PI / 180);
const W0 = 240, H0 = 190, SOLE0 = 150, P = { x: W0 / 2, y: 0, yaw: -Math.PI / 4 }; // the card's cell, before the crop
const SHADOW = [11, 7, 16, 130]; // the foes' ground shadow (src/enemy.ts), on the rim
const FOOT = { idle: [0, -1, 10, 8], speak: [-2, 6, 11, 15], beast: [0, 4, 12, 18] }; // its centre and radii by pose

const FRAMES = [
  ...[0, 0.5, 1, 0.5].map((k, i) => [`idle${i}`, 'idle', k]),
  ...[0, 0.5, 1, 0.5].map((k, i) => [`look${i}`, 'speak', k]),
  ...[0, 1].map((k, i) => [`beast${i}`, 'beast', k]),
];

function frame([, pose, k]) {
  const m = bassin(pose, k), lift = m.lift, at = (p) => { const q = place(P, p); return [q[0], q[1], q[2] + lift]; };
  const light = (l) => ({ soft: 5, R: 200, pad: 1, ...l, p: at(l.p) });
  const sc = {
    W: W0, H: H0, cam, off: -SOLE0, env: null, ambient: L('#1a1c1e').map((c) => c * 0.6),
    objects: [{ name: 'him', pos: [P.x, P.y, lift], yaw: P.yaw, ...m, id: 60 }], // the basin (m.subs) is the room's own
    lights: [
      light({ p: [63.6, -21.2, 75], c: L('#8098a2'), I: 8, r0: 90, R: 260, soft: 10, only: ['him'] }), // cold back light
      light({ p: [-99, 99, 140 - lift], c: L('#a08a70'), I: 0.9, r0: 130, R: 420, soft: 12 }),
      light({ p: [-15.6, 55.2, 60], c: L('#b8a68a'), I: 2.4, r0: 40, R: 170, soft: 6 }), // the hero's lantern, off-frame
      ...m.lights.map(light), // his eyes' glow on his face
    ],
  };
  const img = render(sc);
  haze(img, sc);
  const px = post(img, { exposure: 3.3, vignette: 0, desat: 0.15, grain: 0.004, dither: 0.015 });
  for (let p = 0; p < W0 * H0; p++) px[p * 4 + 3] = img.oid[p] >= 0 ? 255 : 0;
  // His contact shadow on the rim: an ellipse on the plane he stands on round his feet (and hands), in his own frame
  // (x left, y forward, ghoul units), where he does not cover it; soft at its edge.
  const [ex, ey, rx, ry] = FOOT[pose], c = Math.cos(P.yaw), s = Math.sin(P.yaw);
  for (let y = 0; y < H0; y++) for (let x = 0; x < W0; x++) {
    const dx = x + 0.5 - P.x, dy = (y + 0.5 - SOLE0 + lift * cam.c) / cam.s - P.y; // the pixel, on the rim's plane
    const d = Math.hypot((c * dx + s * dy - ex) / rx, (-s * dx + c * dy - ey) / ry);
    if (d < 1 && !px[(y * W0 + x) * 4 + 3]) px.set([...SHADOW.slice(0, 3), Math.round(SHADOW[3] * Math.min(1, 3 * (1 - d)))], (y * W0 + x) * 4);
  }
  return px;
}

const t0 = Date.now(), cells = FRAMES.map(frame);
// Crop every cell to the box all frames cover, a pixel of air round it.
let x0 = W0, y0 = H0, x1 = 0, y1 = 0;
for (const px of cells) for (let p = 0; p < W0 * H0; p++) if (px[p * 4 + 3]) {
  const x = p % W0, y = (p - x) / W0;
  [x0, y0, x1, y1] = [Math.min(x0, x), Math.min(y0, y), Math.max(x1, x), Math.max(y1, y)];
}
// Centred on his floor point, so mirroring keeps it in place.
const half = Math.max(P.x - x0, x1 + 1 - P.x) + 1, FW = 2 * half, FH = y1 - y0 + 3, top = y0 - 1, left = P.x - half;
const rgba = new Uint8ClampedArray(FW * FH * FRAMES.length * 4);
cells.forEach((px, i) => {
  for (let y = 0; y < FH; y++) for (let x = 0; x < FW; x++) {
    const sx = left + x, sy = top + y;
    if (sx >= 0 && sx < W0 && sy >= 0 && sy < H0) rgba.set(px.subarray((sy * W0 + sx) * 4, (sy * W0 + sx) * 4 + 4), (y * FW * FRAMES.length + i * FW + x) * 4);
  }
});
const W = FW * FRAMES.length;
if (process.env.PREVIEW) {
  for (let p = 0; p < W * FH; p++) if (!rgba[p * 4 + 3]) rgba.set([70, 70, 74, 255], p * 4);
  mkdirSync('shots', { recursive: true });
  writePNG('shots/ronge-preview.png', rgba, W, FH, 2);
} else {
  writePNG('src/ronge.png', rgba, W, FH);
  writeFileSync('src/ronge.data.ts', `// Generated by tools/art/ronge.gen.mjs: edit the model there, not this table.
// Le Rongé's sheet (src/ronge.png): one row of FW x FH cells, his floor point (under the basin's rim he perches on) on
// row SOLE, centred; facing down-right.
export const FW = ${FW}, FH = ${FH}, SOLE = ${SOLE0 - top};
export const FRAMES = ${JSON.stringify(FRAMES.map(([n]) => n))};
`);
}
console.log(`${FRAMES.length} frames ${FW}x${FH}, floor point on row ${SOLE0 - top}, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
