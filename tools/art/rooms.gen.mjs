// A run room in the « grand pixel » style for the game, baked from its 3D scene (tools/art/rooms/<id>.mjs, the mockup
// engine) the way tools/art/refuge.gen.mjs bakes the refuge (tools/art/bake.mjs): src/<id>-albedo.png (what the world
// camera draws, two texels per room px), src/<id>-light.png (dark.ts's three bands of light), src/<id>-over.png (what
// stands in front of the floor cut into sprites by floor row, the front wall over the stairs, the portcullis' frames as
// it rises) and src/<id>.data.ts (the scene's gameplay plan, unchanged from the painted room it replaces, the sprites,
// the flames and, open to the sky, the floor the Dawn burns: the same shadows the render paints).
// Usage: node tools/art/rooms.gen.mjs <crypt|cloister> [--fresh] (re-renders; the render is cached in shots/<id>.cache)
// Also writes shots/<id>-preview.png (lit as the mockups post it, no hero) and shots/<id>-walk.png (the plan over it).
import { isMainThread, parentPort, workerData } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import { render, haze, post } from './maquettes/hub3/lib.mjs';
import { renderAll, posted, bands, cut, pack, png } from './bake.mjs';

const id = isMainThread ? process.argv[2] : workerData.id;
const S = await import(`./rooms/${id}.mjs`);
const sc = await S.scene();
const { W, H } = sc, N = W * H, P = S.PLAN, { RW, RH } = P, SN = sc.cam.s, CS = sc.cam.c;

if (!isMainThread) { // a worker: every NW-th row
  sc.rowN = workerData.NW; sc.rowK = workerData.k;
  parentPort.postMessage(posted(render(sc)));
} else {
  const img = await renderAll(new URL(import.meta.url), { id }, W, H, `shots/${id}.cache`, process.argv.includes('--fresh'));
  bake({ ...img, W, H });
}

function bake(img) {
  S.finish?.(img, sc); // what the scene adds over its render (the crypt's moon shafts)
  const hz = { W, H, out: new Float32Array(3 * N) };
  haze(hz, sc);

  // ---- the plan: where walkers go, and, under the sky, where the Dawn burns ----
  const inBox = (x, y, [bx, by, bw, bh]) => x >= bx && x < bx + bw && y >= by && y < by + bh;
  const walk = new Uint8Array(RW * RH);
  for (let y = 0; y < RH; y++) for (let x = 0; x < RW; x++)
    walk[y * RW + x] = inBox(x + 0.5, y + 0.5, P.BOUNDS) && ![...P.BOXES, ...P.PITS.map((b) => [b.x, b.y, b.w, b.h])].some((b) => inBox(x + 0.5, y + 0.5, b)) ? 1 : 0;
  let holy = '';
  if (P.HOLY) holy = dawn(img);

  // ---- the light, then what stands in front: by floor row, and the front wall over the stairs, always on top ----
  const { albedo, light, Yrow, Z } = bands(img, W, H, SN, CS, 0, hz.out);
  const front = 2 * P.FY1;
  const sprites = cut(walk, RW, RH, W, H, Yrow, Z, (i) => i >= front * W);
  const frontBand = { depth: 7970, x0: 0, y0: front, x1: W - 1, y1: H - 1, px: Array.from({ length: (H - front) * W }, (_, k) => front * W + k) };
  // ---- the portcullis rising, 3 room px a frame: its texels wherever any frame differs from the closed one ----
  const [gx0, gy0, gx1, gy1] = P.GATEBOX.map((v) => 2 * v), gw = gx1 - gx0, gh = gy1 - gy0, frames = [];
  sc.clip = [gx0, gy0, gx1, gy1];
  for (let d = 0; d <= P.GATE_RISE; d += 3) {
    S.raise(sc, d);
    const r = render(sc), f = new Uint8ClampedArray(gw * gh * 4);
    for (let y = 0; y < gh; y++) for (let x = 0; x < gw; x++) for (let k = 0; k < 3; k++)
      f[(y * gw + x) * 4 + k] = Math.round(Math.min(1, r.alb3[((gy0 + y) * W + gx0 + x) * 3 + k]) ** (1 / 2.2) * 255);
    frames.push(f);
  }
  S.raise(sc, 0); delete sc.clip;
  for (let i = 0; i < gw * gh; i++) {
    const on = frames.some((f) => f[i * 4] !== frames[0][i * 4] || f[i * 4 + 1] !== frames[0][i * 4 + 1] || f[i * 4 + 2] !== frames[0][i * 4 + 2]);
    for (const f of frames) f[i * 4 + 3] = on ? 255 : 0;
  }
  const gates = frames.map((rgba) => ({ x0: gx0, y0: gy0, x1: gx1 - 1, y1: gy1 - 1, rgba }));
  const { atlas, AW, AH } = pack([...sprites, frontBand, ...gates], albedo, W);

  png(`src/${id}-albedo.png`, albedo, W, H);
  png(`src/${id}-light.png`, light, W, 3 * H);
  png(`src/${id}-over.png`, atlas, AW, AH, true);
  const pal = S.PAL.map((c) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join(''));
  const J = JSON.stringify;
  writeFileSync(`src/${id}.data.ts`, `// Generated by tools/art/rooms.gen.mjs from tools/art/rooms/${id}.mjs: edit the scene there, not this table.
// Room px (two texels of src/${id}-*.png each). W x H: the room; BOUNDS: where feet go (x, y, w, h); FY1: its floor's front
// edge. BOXES: the solid props' footprints (x, y, w, h); PITS: what walkers go round and shots fly over. START, SPAWNS,
// SPOTS (the Order's lanterns), SECTIONS (feet lines into the next part, bottom first), GIFT, GATE, STAIRS: as RoomScene
// reads them from a room. OVER: the sprites cut from src/${id}-over.png, atlas x, y, w, h (texels), where they go
// (texels), their depth; GATES: the portcullis' frames there, closed to raised, atlas x, y, then where (texels), w, h.
// TORCHES: flames drawn over the dark (dark.ts). HOLY: the floor the Dawn burns, row by row from row 0, lengths of runs
// out of it and in it in turn (base 36), '' if none. PALETTE: the mockup's, for dark.ts.
export const W = ${RW}, H = ${RH}, FY1 = ${P.FY1};
export const BOUNDS: [number, number, number, number] = ${J(P.BOUNDS)};
export const START = ${J(P.START)}, GIFT = ${J(P.GIFT)}, GATE = ${J(P.GATE)}, STAIRS = ${J(P.STAIRS)};
export const SPAWNS = ${J(P.SPAWNS)};
export const SPOTS = ${J(P.SPOTS)};
export const SECTIONS = ${J(P.SECTIONS)};
export const BOXES: [number, number, number, number][] = ${J(P.BOXES)};
export const PITS: { x: number; y: number; w: number; h: number }[] = ${J(P.PITS)};
export const OVER: [number, number, number, number, number, number, number][] = ${J([...sprites, frontBand].map((g) => [g.ax, g.ay, g.x1 - g.x0 + 1, g.y1 - g.y0 + 1, g.x0, g.y0, g.depth]))};
export const GATES = { at: [${gx0}, ${gy0}], w: ${gw}, h: ${gh}, frames: ${J(gates.map((g) => [g.ax, g.ay]))} as [number, number][] };
export const TORCHES: [number, number, number][] = ${J(P.TORCHES)};
export const HOLY = '${holy}';
export const PALETTE = ${J(pal)};
`);

  // Checks: the mockup's own post over the bake (no hero, no moving light); the plan over the albedo.
  const pre = post({ ...img, out: img.out.map((v, i) => v + hz.out[i]), emis: img.emi.filter((_, i) => i % 3 === 0).map((v, i) => v + img.emi[i * 3 + 1] + img.emi[i * 3 + 2]) }, { ...S.POST, palette: S.PAL });
  png(`shots/${id}-preview.png`, pre, W, H);
  const chk = Uint8ClampedArray.from(albedo), dot = (x, y, c) => { if (x >= 0 && y >= 0 && x < W && y < H) chk.set(c, (y * W + x) * 4); };
  for (let y = 0; y < RH; y++) for (let x = 0; x < RW; x++) if (walk[y * RW + x] && (x + y) % 3 === 0) dot(2 * x, 2 * y, [60, 200, 60, 255]);
  for (const [x, y, w, h] of [...P.BOXES, ...P.PITS.map((b) => [b.x, b.y, b.w, b.h])]) for (let k = 0; k < 2 * w; k++) { dot(2 * x + k, 2 * y, [220, 40, 40, 255]); dot(2 * x + k, 2 * (y + h) - 1, [220, 40, 40, 255]); }
  for (const p of [P.START, ...P.SPAWNS]) for (let d = -4; d <= 4; d++) { dot(2 * p.x + d, 2 * p.y, [80, 160, 255, 255]); dot(2 * p.x, 2 * p.y + d, [80, 160, 255, 255]); }
  for (const p of P.SPOTS) for (let d = -3; d <= 3; d++) { dot(2 * p.x + d, 2 * p.y + d, [240, 220, 40, 255]); dot(2 * p.x + d, 2 * p.y - d, [240, 220, 40, 255]); }
  png(`shots/${id}-walk.png`, chk, W, H);
  console.log(`${id} ${RW}x${RH} room px: ${sprites.length} sprites, atlas ${AW}x${AH}, ${frames.length} gate frames`);
}

/** The floor the Dawn burns, per room px: the scene's 'sun' light reaches it through the same shadow rays as the
 *  render. Its rim, one texel on the lit side, is painted raw yellow into the render (as the mockup does), so the
 *  burning edge is the one drawn; and visible floor texels are checked against it. Returns its runs. */
function dawn(img) {
  const sun = sc.lights.find((l) => l.mask);
  sc.clip = [0, 0, 0, 0]; render(sc); delete sc.clip; // sets up the scene's shadow()
  const lit = new Uint8Array(RW * RH);
  for (let y = 0; y < RH; y++) for (let x = 0; x < RW; x++) {
    const px = 2 * x + 1, py = (2 * y + 1) / SN;
    lit[y * RW + x] = sc.shadow(px, py, 0.3, ...sun.p, sun) >= 0.5 ? 1 : 0;
  }
  // visible floor texels whose render says otherwise
  let floorT = 0, dark = 0, bright = 0;
  for (let i = 0; i < N; i++) {
    const t = img.depth[i], py = (i / W) | 0, z = -(py + 0.5) * CS + SN * 4000 - SN * t;
    if (t > 1e8 || Math.abs(z) > 0.5) continue;
    const r = lit[(py >> 1) * RW + ((i % W) >> 1)];
    floorT++;
    if (r && img.sun[i] < 0.05) dark++; // burns, painted in shade
    if (!r && img.sun[i] > 0.5) bright++; // safe, painted in the sun
  }
  console.log(`dawn: of the visible floor's texels, ${(100 * dark / floorT).toFixed(2)} % burn though painted in shade, ${(100 * bright / floorT).toFixed(2)} % are safe though painted in the sun`);
  // the rim: lit texels of a lit room px touching a shaded one
  const at = (x, y) => (x >= 0 && y >= 0 && x < RW && y < RH ? lit[y * RW + x] : 1);
  for (let i = 0; i < N; i++) {
    const tx = i % W, ty = (i / W) | 0, x = tx >> 1, y = ty >> 1;
    if (!lit[y * RW + x] || img.depth[i] > 1e8) continue;
    const nx = tx & 1 ? x + 1 : x - 1, ny = ty & 1 ? y + 1 : y - 1;
    if (at(nx, y) && at(x, ny)) continue;
    img.out[i * 3] *= 1.2; img.out[i * 3 + 1] *= 0.95; img.out[i * 3 + 2] *= 0.35;
  }
  const rows = [];
  for (let y = 0; y < RH; y++) {
    const runs = [];
    let v = 0, n = 0;
    for (let x = 0; x < RW; x++) { if (lit[y * RW + x] === v) n++; else { runs.push(n); v ^= 1; n = 1; } }
    runs.push(n);
    rows.push(runs.map((k) => k.toString(36)).join(','));
  }
  return rows.join(';');
}
